// Builds engine/icons.js from Lucide icons in react-icons. Add names to LIST and re-run:
//   node tools/build-icons.cjs   (needs react, react-dom, react-icons installed)
const path = require('path');
const req = (m) => { try { return require(m); } catch { return require(path.join('/opt/npm-tools/node_modules', m)); } };
const React = req('react'); const { renderToStaticMarkup } = req('react-dom/server'); const lu = req('react-icons/lu');
const LIST = {
  store:'LuStore', cart:'LuShoppingCart', bag:'LuShoppingBag', tag:'LuTag', package:'LuPackage', truck:'LuTruck', receipt:'LuReceipt',
  card:'LuCreditCard', wallet:'LuWallet', coins:'LuCoins', dollar:'LuDollarSign', percent:'LuPercent', gift:'LuGift',
  search:'LuSearch', eye:'LuEye', spy:'LuScanEye', target:'LuTarget', radar:'LuRadar', scan:'LuScanSearch',
  bot:'LuBot', brain:'LuBrain', sparkles:'LuSparkles', wand:'LuWandSparkles', cpu:'LuCpu', zap:'LuZap', workflow:'LuWorkflow',
  chart:'LuChartColumn', trending:'LuTrendingUp', down:'LuTrendingDown', gauge:'LuGauge', activity:'LuActivity', timer:'LuTimer', clock:'LuClock',
  phone:'LuSmartphone', laptop:'LuLaptop', monitor:'LuMonitor', globe:'LuGlobe', link:'LuLink', code:'LuCode', terminal:'LuTerminal',
  mail:'LuMail', inbox:'LuInbox', send:'LuSend', message:'LuMessageCircle', bell:'LuBell', megaphone:'LuMegaphone',
  star:'LuStar', heart:'LuHeart', thumbs:'LuThumbsUp', users:'LuUsers', user:'LuUser', shield:'LuShieldCheck', lock:'LuLock',
  check:'LuCheck', checkCircle:'LuCircleCheck', x:'LuX', xCircle:'LuCircleX', alert:'LuTriangleAlert', help:'LuCircleHelp', info:'LuInfo',
  snail:'LuSnail', rocket:'LuRocket', flame:'LuFlame', trophy:'LuTrophy', crown:'LuCrown', lightbulb:'LuLightbulb', key:'LuKey',
  image:'LuImage', camera:'LuCamera', video:'LuVideo', file:'LuFileText', folder:'LuFolder', list:'LuListChecks', calendar:'LuCalendar',
  map:'LuMapPin', filter:'LuFilter', layers:'LuLayers', box:'LuBox', settings:'LuSettings', refresh:'LuRefreshCw', arrowRight:'LuArrowRight',
  pointer:'LuMousePointerClick', hand:'LuHand', play:'LuPlay', bug:'LuBug', droplet:'LuDroplets', magnet:'LuMagnet', puzzle:'LuPuzzle'
};
const out = {}; const missing = [];
for (const [k, n] of Object.entries(LIST)) {
  if (!lu[n]) { missing.push(n); continue; }
  out[k] = renderToStaticMarkup(React.createElement(lu[n], { size: '100%' })).replace(/<svg /, '<svg class="ic" ');
}
require('fs').writeFileSync(path.join(__dirname, '../engine/icons.js'),
  '// Generated by tools/build-icons.cjs (Lucide icons, ISC license)\nwindow.ICONS = ' + JSON.stringify(out) + ';\n');
console.log('icons:', Object.keys(out).length, 'missing:', missing.join(', ') || 'none');
